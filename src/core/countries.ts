export function ownerName(code: string): string | null {
  return OWNERS[code.trim().toUpperCase()] ?? null;
}

/** Görünen ad: bilinen kodda Türkçe ad, bilinmeyende "Kod: XYZ". */
export function ownerDisplay(code: string | null): string | null {
  if (!code) return null;
  return ownerName(code) ?? `Sahip kodu: ${code}`;
}
